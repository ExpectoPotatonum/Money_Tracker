export function setLocale(lang) {
  current = lang in DICT ? lang : 'en';
  saveSettings({ lang: current });
}

export function t(key) {
  const table = DICT[locale()] ?? DICT.en;
  return table[key] ?? DICT.en[key] ?? key;
}
